export async function addAdminVoice(req: AuthenticatedRequest, res: Response, next: NextFunction): Promise<void> {
  try {
    const { name, lang, gender, accent, style, featured } = req.body;
    
    // Check if voice name exists
    const existing = await prisma.voice.findUnique({ where: { name } });
    if (existing) {
      res.status(400).json({ success: false, message: "Voice name already exists." });
      return;
    }

    const newVoice = await prisma.voice.create({
      data: {
        name,
        gender: gender || "Female",
        category: style || "Standard",
        accent: accent || "Global",
        age: "Adult",
        featured: featured || false,
        providerName: "local"
      }
    });
    res.status(201).json({ success: true, data: newVoice });
  } catch (error) {
    next(error);
  }
}

